async function assertLargeTokenPainted(page: Page, actor: Actor, side: 2 | 3, camera: Awaited<ReturnType<typeof fittedMap>>) {
  await expect(page.locator('.battle-map canvas')).toBeVisible();
  const offsets = side === 2 ? [[.5, .5], [1.5, .5], [.5, 1.5], [1.5, 1.5]] : [[.5, 1.5], [2.5, 1.5], [1.5, .5], [1.5, 2.5]];
  await expect.poll(async () => {
    const { data, width } = PNG.sync.read(await page.locator('.battle-map').screenshot());
    return offsets.map(([dx, dy]) => {
      const point = camera.point(actor.position.x + dx, actor.position.y + dy);
      const index = (Math.round(point.y - camera.box.y) * width + Math.round(point.x - camera.box.x)) * 4;
      return [data[index], data[index + 1], data[index + 2]];
    });
  }, { message: `${actor.name} at ${JSON.stringify(actor.position)} must render across its actual ${side}×${side} footprint` }).toEqual(offsets.map(() => [83, 61, 67]));
  if (process.env.CLIENT_SCREENSHOT_DIR) await page.screenshot({ path: join(process.env.CLIENT_SCREENSHOT_DIR, `large-${side}-diagnostic.png`), fullPage: true });
}
