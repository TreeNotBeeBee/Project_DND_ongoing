const { PNG } = createRequire(import.meta.url)('pngjs');
async function assertMapPainted(page: Page) {
  await expect.poll(async () => {
    const buffer = await page.locator('.battle-map').screenshot({ animations: 'disabled' });
    const { data, width, height } = PNG.sync.read(buffer); let floor = 0, token = 0;
    for (let index = 0; index < data.length; index += 4) {
      if (data[index] === 27 && data[index + 1] === 34 && data[index + 2] === 44 || data[index] === 32 && data[index + 1] === 40 && data[index + 2] === 51) floor++;
      if (data[index] >= 30 && data[index] <= 55 && data[index + 1] >= 45 && data[index + 1] <= 85 && data[index + 2] >= 45 && data[index + 2] <= 85 && data[index + 1] - data[index] >= 12 && data[index + 1] >= data[index + 2] - 4) token++;
    }
    return { grid: floor > width * height * .06, token: token > 10 };
  }, { timeout: 15000, message: 'Rendered map pixels must contain the board floor and a visible hero token' }).toEqual({ grid: true, token: true });
}
